#!/usr/bin/env node
/*
 * Builds public/js/products.js from scripts/catalog.js.
 * Run:  node scripts/generate-products.js
 *
 * You can also edit public/js/products.js by hand once you have your own stock.
 */
const fs = require('fs');
const path = require('path');
const CATALOG = require('./catalog');

const CATEGORIES = [
  { id: 'men', name: "Men's Watches" },
  { id: 'women', name: "Women's Watches" },
  { id: 'smart', name: 'Smartwatches' },
  { id: 'sports', name: 'G-Shock & Sports' },
  { id: 'chrono', name: 'Chronographs' },
  { id: 'premium', name: 'Premium Collection' },
  { id: 'kids', name: 'Kids Watches' },
];

// Deterministic "random" so the output is stable between runs.
let seed = 20260930;
const rand = () => { seed = (seed * 1664525 + 1013904223) % 4294967296; return seed / 4294967296; };
const pick = (a) => a[Math.floor(rand() * a.length)];

const STRAP_LABEL = {
  leather: 'Genuine Leather', metal: 'Stainless Steel Bracelet', jubilee: 'Stainless Steel Bracelet', mesh: 'Milanese Mesh',
  rubber: 'Silicone', resin: 'Resin', fabric: 'Canvas / Fabric', nato: 'Nylon NATO',
};
const STRAP_LINE = {
  leather: 'It comes on a soft genuine leather strap that gets more comfortable with every wear.',
  metal: 'The solid stainless steel bracelet with a secure clasp gives it a premium, weighty feel.',
  jubilee: 'The polished bracelet is as much jewellery as it is a watch.',
  mesh: 'The Milanese mesh bracelet is smooth, breathable and easily adjustable.',
  rubber: 'The soft, sweat-proof silicone strap is comfortable all day and during workouts.',
  resin: 'The tough resin band is light, flexible and made for everyday knocks.',
  fabric: 'The rugged canvas strap is light and breathable.',
  nato: 'The slip-through nylon strap is light, comfy and quick to swap.',
};
const WARRANTY = { Casio: '2 Years', Titan: '2 Years', Fastrack: '1 Year', Sonata: '1 Year', Timex: '1 Year', Fossil: '2 Years', Seiko: '1 Year', Citizen: '1 Year', HMT: '1 Year', TimeVault: '6 Months' };

const products = CATALOG.map((c, i) => {
  const n = i + 1;
  const colorNames = c.v.map((v) => v.name);
  const colourText = colorNames.length > 1 ? `Available in ${colorNames.slice(0, -1).join(', ')} and ${colorNames[colorNames.length - 1]}.` : '';
  const closer = pick([
    'Comes in a gift box with warranty card - perfect for birthdays, anniversaries and festivals.',
    '100% genuine product with brand warranty and easy returns.',
    'A great gift for yourself or someone special.',
    'Ships in original packaging with warranty card.',
  ]);
  const pop = c.pop || 6;
  const reviews = Math.round(pop * pop * (8 + rand() * 18));
  return {
    id: `w${String(n).padStart(3, '0')}`,
    sku: c.ref,
    name: `${c.b} ${c.m}`,
    brand: c.b,
    model: c.m,
    category: c.cat,
    audience: c.cat === 'women' ? 'women' : c.cat === 'kids' ? 'kids' : 'unisex',
    price: c.p,
    mrp: c.mrp,
    rating: Math.min(4.9, Math.round((3.9 + pop * 0.09 + rand() * 0.15) * 10) / 10),
    reviews,
    pop,
    stock: pop >= 9 ? 20 + Math.floor(rand() * 40) : rand() < 0.07 ? 0 : 3 + Math.floor(rand() * 30),
    badge: pop >= 10 ? 'Bestseller' : c.p >= 12000 ? 'Premium' : 1 - c.p / c.mrp >= 0.5 ? 'Hot Deal' : pop >= 9 ? 'Top Rated' : '',
    style: c.s,
    strapType: c.st,
    small: !!c.small,
    look: {
      ind: c.ind || 'stick', date: !!c.date, tachy: !!c.tachy, auto: !!c.auto, openheart: !!c.openheart, bezel2: !!c.bezel2,
      labels: c.labels || null,
    },
    colors: c.v.map((v) => ({ ...v, image: '' })),
    description: `${c.blurb} ${STRAP_LINE[c.st]} ${colourText} ${closer}`.replace(/\s+/g, ' ').trim(),
    features: [...c.feats, `${c.wr} water resistance`.replace('Water Resistant water resistance', 'Water resistant (splash-proof)').replace('Splash resistant water resistance', 'Splash resistant')],
    specs: {
      Brand: c.b,
      Model: c.m,
      'Reference No.': c.ref,
      Movement: c.mv,
      'Case / Display Size': c.size,
      Strap: STRAP_LABEL[c.st],
      Glass: c.glass,
      'Water Resistance': c.wr,
      Warranty: WARRANTY[c.b] || '1 Year',
      'In the Box': 'Watch, box, warranty card' + (/Smart|Band/.test(c.mv) ? ', magnetic charger' : ''),
    },
    createdAt: `2026-${String(1 + Math.floor(rand() * 9)).padStart(2, '0')}-${String(1 + Math.floor(rand() * 28)).padStart(2, '0')}`,
  };
});

const out = `/* AUTO-GENERATED by scripts/generate-products.js from scripts/catalog.js - ${products.length} products.
 * You can edit this file by hand to add your own watches.
 * To use a real photo for a colour, put the file in public/images/ and set
 *   "image": "images/your-photo.jpg"
 * on that colour. When image is empty, a drawn illustration of the watch is shown.
 */
window.CATEGORIES = ${JSON.stringify(CATEGORIES, null, 2)};

window.PRODUCTS = ${JSON.stringify(products, null, 2)};
`;
fs.writeFileSync(path.join(__dirname, '..', 'public', 'js', 'products.js'), out);
const prices = products.map((p) => p.price);
const colours = products.reduce((s, p) => s + p.colors.length, 0);
console.log(`Wrote ${products.length} products, ${colours} colour variants. Price range: ${Math.min(...prices)} - ${Math.max(...prices)}`);
CATEGORIES.forEach((c) => console.log(`  ${c.name}: ${products.filter((p) => p.category === c.id).length}`));
